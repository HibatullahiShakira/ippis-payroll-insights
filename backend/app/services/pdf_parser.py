class PdfParseError(Exception):
    """Raised when a payslip PDF yields no usable payslips at all."""


def detect_month_year(filepath, max_pages=5):
    """
    Read the payroll month (e.g. '2026-04') printed on the payslips in a bulk PDF.

    Returns None if the first few pages carry no recognisable month.
    Raises if the file cannot be opened as a PDF.
    """
    import fitz  # PyMuPDF

    with fitz.open(filepath) as doc:
        for page_num in range(min(doc.page_count, max_pages)):
            data = _parse_page_text(doc.load_page(page_num).get_text("text"))
            if data and data.get("extracted_month_year"):
                return data["extracted_month_year"]
    return None


MONEY_TOLERANCE = Decimal("0.05")  # IPPIS rounds printed totals; allow a few kobo
MAX_EXAMPLES = 15


def analyze_pdf(filepath):
    """
    Read a bulk payslip PDF without touching the database and check every payslip
    against itself: the itemised earnings/deductions must add up to the printed
    totals, and Gross - Deductions must equal Net.

    Returns a dict of counts plus example problem pages, and 'ippis' (the set of
    IPPIS numbers found) for comparing against what is already on record.
    """
    import fitz  # PyMuPDF

    result = {
        "pages": 0, "payslips": 0,
        "blank_pages": 0, "overflow_pages": 0, "unrecognised_pages": 0,
        "months": {}, "fully_itemised": 0, "itemised_mismatch": 0, "net_mismatch": 0,
        "missing": {"name": 0, "grade": 0, "gross": 0, "net": 0},
        "duplicates": 0, "examples": [], "ippis": set(),
    }

    def example(page_num, data, issue):
        if len(result["examples"]) < MAX_EXAMPLES:
            result["examples"].append({
                "page": page_num + 1,
                "ippis": (data or {}).get("ippis_number"),
                "name": (data or {}).get("name"),
                "issue": issue,
            })

    with fitz.open(filepath) as doc:
        result["pages"] = doc.page_count
        for page_num in range(doc.page_count):
            text = doc.load_page(page_num).get_text("text") or ""
            if not text.strip():
                result["blank_pages"] += 1
                continue

            data = _parse_page_text(text)
            if not data or not data.get("ippis_number"):
                # Long payslips continue onto a page that has only the page header
                # (its "Generated By: IPPIS SoftSUITE" header is not a payslip field)
                if not re.search(r"Employee\s*Name|IPPIS\s*Number", text, re.IGNORECASE):
                    result["overflow_pages"] += 1
                else:
                    result["unrecognised_pages"] += 1
                    example(page_num, data, "Looks like a payslip but the IPPIS Number could not be read")
                continue

            result["payslips"] += 1
            ippis = data["ippis_number"]
            if ippis in result["ippis"]:
                result["duplicates"] += 1
                example(page_num, data, "IPPIS number appears on more than one payslip in this PDF")
            result["ippis"].add(ippis)

            month = data.get("extracted_month_year")
            if month:
                result["months"][month] = result["months"].get(month, 0) + 1

            if not data.get("name"):
                result["missing"]["name"] += 1
            if not data.get("grade"):
                result["missing"]["grade"] += 1

            gross = data.get("total_gross_earnings")
            deductions = data.get("total_gross_deductions")
            net = data.get("total_net_earnings")
            if gross is None:
                result["missing"]["gross"] += 1
            if net is None:
                result["missing"]["net"] += 1

            if None not in (gross, deductions, net) and abs(gross - deductions - net) > MONEY_TOLERANCE:
                result["net_mismatch"] += 1
                example(page_num, data, f"Gross {gross:,} - Deductions {deductions:,} does not equal Net {net:,}")

            if data.get("itemised_incomplete"):
                result["itemised_mismatch"] += 1
                example(page_num, data, "IPPIS cut the " + " and ".join(data["itemised_incomplete"])
                        + " list short; the rest is saved as 'Not itemised on payslip'")
            else:
                result["fully_itemised"] += 1

    return result


def parse_pdf(filepath, batch_id, month_year, progress_offset=0):
    """
    Parse the bulk payslip PDF file and create Payslip records.

    Every page is read first (no database work), then the payslips are saved in
    batches, with progress recorded on the upload batch after each one.

    Args:
        filepath: Path to the PDF file.
        batch_id: The UploadBatch ID to associate payslips with.
        month_year: The month string (e.g., '2026-04'); the month printed on the
            payslips takes precedence.
        progress_offset: Records already done by an earlier step of the same
            upload (the nominal roll), so the progress bar keeps counting up.

    Returns:
        int: Number of payslips saved.
    """
    from .import_writer import Progress, save_payslips

    # Why pages were skipped, so a bad upload can explain itself
    no_text_pages = 0
    unrecognised_pages = 0
    payslips = []

    import fitz  # PyMuPDF

    with fitz.open(filepath) as doc:
        total_pages = doc.page_count
        for page_num in range(total_pages):
            text = doc.load_page(page_num).get_text("text")
            if not text or not text.strip():
                no_text_pages += 1
                continue
            data = _parse_page_text(text)
            if not data or not data.get("ippis_number"):
                unrecognised_pages += 1
                continue
            data["pdf_page_num"] = page_num
            payslips.append(data)

    # The month printed on the payslips wins
    if payslips and payslips[0].get("extracted_month_year"):
        month_year = payslips[0]["extracted_month_year"]

    count, failed_pages, first_error = save_payslips(
        payslips, month_year, batch_id, progress=Progress(batch_id, progress_offset)
    )

    if count == 0 and total_pages > 0:
        reasons = []
        if failed_pages:
            reasons.append(f"{failed_pages} payslip(s) could not be saved (first error, {first_error})")
        if unrecognised_pages:
            reasons.append(f"{unrecognised_pages} page(s) had no IPPIS Number in the expected payslip layout")
        if no_text_pages:
            reasons.append(
                f"{no_text_pages} page(s) contain no readable text (the PDF may be a scanned image)"
            )
        raise PdfParseError(
            f"No payslips could be read from the {total_pages}-page PDF: " + "; ".join(reasons) + "."
        )
    if failed_pages:
        print(f"{failed_pages} payslip(s) could not be saved; first error: {first_error}")

    return count


def _update_payslip(payslip, data):
    """Update an existing payslip with new data."""
    for field in [
        "grade", "step", "gender", "tax_state", "designation",
        "date_of_birth", "date_of_first_appt", "trade_union",
        "bank_name", "account_number", "pfa_name", "pension_pin",
        "total_gross_earnings", "total_gross_deductions", "total_net_earnings",
        "cumulative_tax", "cumulative_income", "cumulative_pension", "cumulative_nhf",
        "pdf_page_num",
    ]:
        if data.get(field) is not None:
            setattr(payslip, field, data[field])


