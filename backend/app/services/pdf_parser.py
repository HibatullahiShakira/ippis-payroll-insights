def _label_key(text):
    return re.sub(r"[^a-z0-9]+", " ", text.lower()).strip()


_LABEL_TO_FIELD = {}
for _field, _labels in PAYSLIP_LABELS.items():
    for _label in _labels:
        _LABEL_TO_FIELD.setdefault(_label_key(_label), _field)
_STOP_KEYS = set(_LABEL_TO_FIELD) | {_label_key(h) for h in SECTION_HEADINGS}
# Longest labels first, so "Total Gross Earnings" wins over "Gross Earnings"
_SAME_LINE_LABELS = sorted(_LABEL_TO_FIELD, key=len, reverse=True)


def _split_label_line(line):
    """
    Return (field, inline value) if the line is a field label, else None.
    Handles 'IPPIS Number:' alone on a line and 'IPPIS Number: 128045' on one line.
    """
    key = _label_key(line)
    if key in _LABEL_TO_FIELD:
        return _LABEL_TO_FIELD[key], ""
    if ":" in line:
        label, _, value = line.partition(":")
        label_key = _label_key(label)
        if label_key in _LABEL_TO_FIELD and value.strip():
            return _LABEL_TO_FIELD[label_key], value.strip()
    return None


def _read_labelled_fields(text):
    """
    Read 'Label:' / value pairs from payslip text. A value is everything after its
    label up to the next label or heading, so values that wrap ('United Bank For
    Africa' / 'Plc') stay whole and an empty field ('Location:' then 'TIN:') stays empty.
    """
    lines = [l.strip() for l in text.split("\n")]
    values = {}
    i = 0
    while i < len(lines):
        found = _split_label_line(lines[i]) if lines[i] else None
        if not found:
            i += 1
            continue
        field, inline = found
        parts = [inline] if inline else []
        j = i + 1
        while not inline and j < len(lines):
            nxt = lines[j]
            if nxt and (_label_key(nxt) in _STOP_KEYS or _split_label_line(nxt)):
                break
            if nxt:
                parts.append(nxt)
            j += 1
            # Header fields hold at most a few short lines
            if len(parts) >= 3:
                break
        value = re.sub(r"\s+", " ", " ".join(parts)).strip()
        if value and field not in values:
            values[field] = value
        i = j if not inline else i + 1
    return values


def _typed_labelled_fields(text):
    """Labelled values converted to the types the Payslip model stores; unusable values are dropped."""
    raw = _read_labelled_fields(text)
    out = {}

    ippis = re.sub(r"\D", "", raw.get("ippis_number", ""))
    if ippis:
        out["ippis_number"] = int(ippis)
    step = re.match(r"\d+", raw.get("step", ""))
    if step:
        out["step"] = int(step.group())
    grade = re.match(r"[A-Za-z0-9_]+", raw.get("grade", ""))
    if grade:
        out["grade"] = grade.group()
    gender = raw.get("gender", "").upper()
    if gender in ("MALE", "FEMALE", "M", "F"):
        out["gender"] = {"M": "MALE", "F": "FEMALE"}.get(gender, gender)
    for field in ("designation", "tax_state", "trade_union", "bank_name", "pfa_name"):
        if raw.get(field):
            out[field] = raw[field]
    for field in ("date_of_birth", "date_of_first_appt"):
        date = re.search(r"\d{1,2}[-/][A-Za-z]{3}[-/]\d{4}", raw.get(field, ""))
        if date:
            out[field] = date.group()
    for field in ("account_number", "pension_pin"):
        digits = re.match(r"\d+$", raw.get(field, "").replace(" ", ""))
        if digits:
            out[field] = digits.group()
    for field in ("total_gross_earnings", "total_gross_deductions", "total_net_earnings"):
        amount = re.match(r"[\d,]+\.?\d*$", raw.get(field, ""))
        if amount:
            out[field] = _parse_amount(amount.group())
    return out


def _parse_page_text(text):
    """
    Parse a single payslip page's text into structured data.

    Fields are read by their labels first (tolerant of moved or wrapped values and
    renamed labels); the older fixed patterns below fill in anything still missing.
    """
    data = _parse_page_text_patterns(text)
    if data is None:
        labelled = _typed_labelled_fields(text)
        if "ippis_number" not in labelled:
            return None
        data = _parse_page_text_patterns(text, require_ippis=False)
    else:
        labelled = _typed_labelled_fields(text)
    data.update(labelled)
    _account_for_unlisted_items(data)
    return data


NOT_ITEMISED = "Not itemised on payslip"


def _account_for_unlisted_items(data):
    """
    IPPIS cuts very long earnings/deductions lists off at the bottom of the page
    and never prints the rest (the following page is blank apart from the
    letterhead), so the listed items fall short of the printed total. The gap is
    saved as one clearly named line, so every breakdown adds up to its printed
    total and the payslip is marked as not fully itemised.
    """
    data["itemised_incomplete"] = []
    for key, total_key in (("earnings", "total_gross_earnings"), ("deductions", "total_gross_deductions")):
        total = data.get(total_key)
        if total is None:
            continue
        gap = total - sum(item["amount"] for item in data.get(key, []))
        if gap > MONEY_TOLERANCE:
            data.setdefault(key, []).append({"type": NOT_ITEMISED, "amount": gap})
            data["itemised_incomplete"].append(key)


def _parse_page_text_patterns(text, require_ippis=True):
    """
    Parse a single payslip page's text into structured data.

    The text follows the IPPIS SoftSUITE payslip format.
    """
    data = {
        "earnings": [],
        "deductions": [],
    }

    lines = text.split("\n")
    full_text = text

    # --- Extract Month and Year ---
    month_match = re.search(r"(January|February|March|April|May|June|July|August|September|October|November|December)[\s,]+(\d{4})", full_text, re.IGNORECASE)
    if month_match:
        month_str = month_match.group(1).capitalize()
        year_str = month_match.group(2)
        month_map = {
            "January": "01", "February": "02", "March": "03", "April": "04",
            "May": "05", "June": "06", "July": "07", "August": "08",
            "September": "09", "October": "10", "November": "11", "December": "12"
        }
        data["extracted_month_year"] = f"{year_str}-{month_map[month_str]}"

    # --- Extract IPPIS Number ---
    ippis_match = re.search(r"IPPIS\s*Number[:\s]*(\d+)", full_text, re.IGNORECASE)
    if ippis_match:
        data["ippis_number"] = int(ippis_match.group(1))
    elif require_ippis:
        return None

    # --- Extract Employee Name ---
    # Take whatever follows the label up to "Grade", then tidy it: data-entry slips
    # in IPPIS (a stray backtick, double spaces) must not lose the whole name.
    name_match = re.search(
        r"Employee\s*Name\s*:?\s*(.+?)\s*(?:\bGrade\b|\n\s*\n|$)",
        full_text,
        re.IGNORECASE | re.DOTALL,
    )
    if name_match:
        name = name_match.group(1).replace("\n", " ")
        name = re.sub(r"[^A-Za-z\s,.\-']", "", name)
        # Clean up title prefixes that got captured
        name = re.sub(r"\b(Mr|Mrs|Ms|Miss|Dr|Engr|Alh|Chief)\.?(?=\s)", "", name, flags=re.IGNORECASE)
        name = re.sub(r"\s+", " ", name).strip(" ,")
        name = re.sub(r"\s+,", ",", name)
        if name:
            data["name"] = name

    # --- Extract Grade ---
    grade_match = re.search(r"Grade[:\s]*([A-Z0-9_]+)", full_text, re.IGNORECASE)
    if grade_match:
        data["grade"] = grade_match.group(1).strip()

    # --- Extract Step ---
    step_match = re.search(r"Step[:\s]*(\d+)", full_text, re.IGNORECASE)
    if step_match:
        try:
            data["step"] = int(step_match.group(1))
        except ValueError:
            pass

    # --- Extract Gender ---
    gender_match = re.search(r"Gender[:\s]*(MALE|FEMALE)", full_text, re.IGNORECASE)
    if gender_match:
        data["gender"] = gender_match.group(1).upper()

    # --- Extract Tax State ---
    tax_match = re.search(r"Tax\s*State[:\s]*([A-Z]+)", full_text, re.IGNORECASE)
    if tax_match:
        data["tax_state"] = tax_match.group(1).strip()

    # --- Extract Designation ---
    desig_match = re.search(
        r"Designation[:\s]*(.+?)(?:\s*Tax\s*State|\s*$)",
        full_text,
        re.IGNORECASE,
    )
    if desig_match:
        data["designation"] = desig_match.group(1).strip()

    # --- Extract Date of Birth ---
    dob_match = re.search(
        r"Date\s*of\s*Birth\s*[:\s]*(\d{1,2}[-/][A-Z]{3}[-/]\d{4})",
        full_text,
        re.IGNORECASE,
    )
    if dob_match:
        data["date_of_birth"] = dob_match.group(1)

    # --- Extract Date of First Appointment ---
    appt_match = re.search(
        r"Date\s*of\s*First\s*Appt[:\s]*(\d{1,2}[-/][A-Z]{3}[-/]\d{4})",
        full_text,
        re.IGNORECASE,
    )
    if appt_match:
        data["date_of_first_appt"] = appt_match.group(1)

    # --- Extract Trade Union ---
    union_match = re.search(r"Trade\s*Union[:\s]*(.+?)(?:\n|Bank)", full_text, re.IGNORECASE)
    if union_match:
        data["trade_union"] = union_match.group(1).strip()

    # --- Extract Bank Name ---
    bank_match = re.search(r"Bank\s*Name[:\s]*(.+?)(?:\n|PFA|Account)", full_text, re.IGNORECASE)
    if bank_match:
        bank = bank_match.group(1).strip()
        # Clean up trailing text
        bank = re.sub(r"\s*(PFA|Pension|Account).*", "", bank, flags=re.IGNORECASE).strip()
        data["bank_name"] = bank

    # --- Extract Account Number ---
    acct_match = re.search(r"Account\s*Number[:\s]*(\d+)", full_text, re.IGNORECASE)
    if acct_match:
        data["account_number"] = acct_match.group(1)

    # --- Extract PFA Name ---
    pfa_match = re.search(r"PFA\s*Name[:\s]*(.+?)(?:\n|Pension\s*PIN|Account)", full_text, re.IGNORECASE)
    if pfa_match:
        pfa = pfa_match.group(1).strip()
        pfa = re.sub(r"\s*(Pension|Account).*", "", pfa, flags=re.IGNORECASE).strip()
        data["pfa_name"] = pfa

    # --- Extract Pension PIN ---
    pin_match = re.search(r"Pension\s*PIN[:\s]*(\d+)", full_text, re.IGNORECASE)
    if pin_match:
        data["pension_pin"] = pin_match.group(1)

    # --- Extract Summary Totals ---
    gross_earn_match = re.search(
        r"Total\s*Gross\s*Earnings?\s*[:\s]*([\d,]+\.?\d*)",
        full_text,
        re.IGNORECASE,
    )
    if gross_earn_match:
        data["total_gross_earnings"] = _parse_amount(gross_earn_match.group(1))

    gross_ded_match = re.search(
        r"Total\s*Gross\s*Deductions?\s*[:\s]*([\d,]+\.?\d*)",
        full_text,
        re.IGNORECASE,
    )
    if gross_ded_match:
        data["total_gross_deductions"] = _parse_amount(gross_ded_match.group(1))

    net_match = re.search(
        r"Total\s*Net\s*Earnings?[:\s]*([\d,]+\.?\d*)",
        full_text,
        re.IGNORECASE,
    )
    if net_match:
        data["total_net_earnings"] = _parse_amount(net_match.group(1))

    # --- Extract Cumulative Balances ---
    # These appear as: Cummulative Tax Deduct | Cummulative Income | Cummulative Pension | Cummulative NHF
    # followed by values on the next line
    cum_match = re.search(
        r"Cummulative\s*Tax.*?Cummulative\s*NHF\s*\n?\s*([\d,]+\.?\d*)\s+([\d,]+\.?\d*)\s+([\d,]+\.?\d*)\s+([\d,]+\.?\d*)",
        full_text,
        re.IGNORECASE | re.DOTALL,
    )
    if cum_match:
        data["cumulative_tax"] = _parse_amount(cum_match.group(1))
        data["cumulative_income"] = _parse_amount(cum_match.group(2))
        data["cumulative_pension"] = _parse_amount(cum_match.group(3))
        data["cumulative_nhf"] = _parse_amount(cum_match.group(4))

    # --- Extract Earnings Items ---
    # Find text between "Earnings Amount" and "Total<number>" in the earnings section
    earnings_section = re.search(
        r"Earnings\s+Amount\s*\n(.+?)Total\s*([\d,]+\.?\d*)\s*Gross\s*Deductions",
        full_text,
        re.IGNORECASE | re.DOTALL,
    )
    if earnings_section:
        earnings_text = earnings_section.group(1)
        data["earnings"] = _parse_line_items(earnings_text)

    # --- Extract Deduction Items ---
    deductions_section = re.search(
        # Very long deduction lists run off the page with no Total line; keep what is there
        r"Deductions\s+Amount\s*\n(.+?)(?:Total\s*([\d,]+\.?\d*)|\Z)",
        full_text,
        re.IGNORECASE | re.DOTALL,
    )
    if deductions_section:
        deductions_text = deductions_section.group(1)
        data["deductions"] = _parse_line_items(deductions_text)

    return data


def _parse_line_items(text):
    """
    Parse earning/deduction line items from a text block.

    Handles both layouts the PDF text can take:
        "Pension 20,713.33"              (description and amount on one line)
        "Pension" / "20,713.33"          (amount on the line after the description)
    Descriptions that wrap over several lines are joined back together.
    """
    items = []
    pending = []  # description lines waiting for their amount

    def add(description, amount_str):
        amount = _parse_amount(amount_str)
        # Skip "Total" lines
        if description and amount is not None and not description.lower().startswith("total"):
            items.append({"type": description, "amount": amount})

    lines = [l.strip() for l in text.strip().split("\n") if l.strip()]
    for i, line in enumerate(lines):
        if AMOUNT_ONLY_RE.match(line):
            if pending:
                add(" ".join(pending), line)
                pending = []
            continue

        # When the next line is an amount on its own, this whole line is the name,
        # even if it ends in a number ("Conhess Shift Allowance 1" / "22,046.00").
        next_is_amount = i + 1 < len(lines) and AMOUNT_ONLY_RE.match(lines[i + 1])

        # Match: description followed by amount (with optional commas and decimal)
        match = re.match(r"(.+?)\s+([\d,]+\.?\d*)$", line)
        if match and not pending and not next_is_amount:
            add(match.group(1).strip(), match.group(2))
        else:
            pending.append(line)

    return items


def _parse_amount(amount_str):
    """Parse a formatted amount string (e.g., '257,481.75') into a Decimal."""
    if not amount_str:
        return None
    try:
        cleaned = amount_str.replace(",", "").strip()
        return Decimal(cleaned)
    except (InvalidOperation, ValueError):
        return None

